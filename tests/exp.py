import os as _os
HERE = _os.path.dirname(_os.path.abspath(__file__))
APP = _os.path.join(HERE, "..", "app")
TOOLS = _os.path.join(HERE, "..", "tools")
import asyncio, threading, http.server, functools, json
from playwright.async_api import async_playwright
srv = http.server.ThreadingHTTPServer(("127.0.0.1", 8770), functools.partial(http.server.SimpleHTTPRequestHandler, directory=APP))
threading.Thread(target=srv.serve_forever, daemon=True).start()
MOCK = open(_os.path.join(HERE, "mock.js")).read()
res = []
def check(n, c, x=""): res.append(c); print("PASS" if c else "FAIL", n, x)
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path="/usr/bin/google-chrome", args=["--no-sandbox"])
        ctx = await b.new_context(viewport={"width": 1280, "height": 900}); await ctx.add_init_script(MOCK)
        pg = await ctx.new_page(); errs = []
        pg.on("pageerror", lambda e: errs.append(str(e)))
        # this suite exercises an unplayed R3: serve the seed with R3's result stripped
        async def unplay(route):
            d = json.load(open(APP + "/expedition-seed.json"))
            w = [w for w in d["weeks"] if w["id"] == "2026-11-16"][0]; r = w["rounds"][2]
            for k in ("result", "score", "laneResults", "stats", "theirStats"): r.pop(k, None)
            r["status"] = "planned"; w["final"] = False
            await route.fulfill(status=200, content_type="application/json", body=json.dumps(d))
        await pg.route("**/expedition-seed.json*", unplay)
        await pg.goto("http://127.0.0.1:8770/index.html#expedition"); await pg.wait_for_timeout(1500)
        weeks = await pg.eval_on_selector("#exp-week", "s=>[...s.options].map(o=>o.text)")
        check("3 weeks listed, newest first, shown by their Tuesday", weeks == ["Week of Nov 17 (in progress)", "Week of Nov 10", "Week of Nov 3"] or (len(weeks) == 3 and "17" in weeks[0] and "Nov 3" in weeks[2]), str(weeks))
        tabs = await pg.eval_on_selector_all("#exp-rounds .buildtabs button", "bs=>bs.map(b=>b.innerText)")
        check("round tabs", len(tabs) == 3 and "Holymoly" in tabs[2], str(tabs))
        sel = await pg.eval_on_selector_all("#exp-rounds .buildtabs button", "bs=>bs.map(b=>b.getAttribute('aria-pressed'))")
        check("opens on the current round (unplayed R3)", sel == ["false", "false", "true"], str(sel))
        await pg.click("#exp-rounds .buildtabs button:nth-child(1)"); await pg.wait_for_timeout(200)
        board = await pg.inner_text("#exp-rounds")
        check("R1 board shows both sides + results", "UkraineArchers" in board and "swagginpanda" in board and "Hago26" in board and "won" in board)
        await pg.screenshot(path="/tmp/shots/exp-r1.png", full_page=False)
        # R3 (locked, predicted their lanes)
        await pg.click("#exp-rounds .buildtabs button:nth-child(3)"); await pg.wait_for_timeout(200)
        t = await pg.inner_text("#exp-rounds")
        check("R3 shows matchup estimates", "favored" in t or "coin flip" in t, t[:200])
        await pg.click("text=Want a suggested lineup?"); await pg.click("text=Suggest lineups"); await pg.wait_for_timeout(300)
        t = await pg.inner_text("#exp-rounds")
        check("suggestions render 2 options with expected flags", "Spread" in t and "Stack two" in t and "expected flags" in t)
        await pg.screenshot(path="/tmp/shots/exp-suggest.png", full_page=True)
        # edit lineup (officer)
        await pg.click("#exp-rounds >> text=Edit lineup"); await pg.wait_for_timeout(200)
        n = await pg.locator("#exp-rounds .lanecard.ours select").count()
        check("lineup editor: 24 slots", n == 24, str(n))
        await pg.select_option("#exp-rounds .lanecard.ours select >> nth=0", "")
        await pg.wait_for_timeout(100)
        await pg.click("text=Save lineup"); await pg.wait_for_timeout(400)
        wk = await pg.evaluate("JSON.stringify(window.__store.get('expedition/2026-11-16'))")
        r3 = await pg.evaluate("JSON.stringify(window.__store.get('expedition/2026-11-16/rounds/3'))")
        check("lineup saved: week header + its own round record", wk and "rounds" not in json.loads(wk) and r3 and '"Hago26"' in r3 and len(json.loads(r3)["our"]["left"]["players"]) == 7)
        # played rounds: read-only, details button works, names link
        await pg.click("#exp-rounds .buildtabs button:nth-child(2)"); await pg.wait_for_timeout(200)
        t = await pg.inner_text("#exp-rounds")
        check("played round has no edit buttons", "Edit lineup" not in t and "Log results" not in t and "Edit results" not in t)
        await pg.click("text=Round details"); await pg.wait_for_timeout(100)
        t = await pg.inner_text("#exp-rounds")
        check("round details read-only", "Their anchor" in t or "THEIR ANCHOR" in t)
        await pg.click("#exp-rounds .lanecard.theirs .linkbtn >> nth=0"); await pg.wait_for_timeout(500)
        opened = await pg.evaluate("[...document.querySelectorAll('#exp-opponents details.inv')].filter(d=>d.open).map(d=>d.querySelector('summary').innerText)")
        check("guild link opens that opponent", len(opened) == 1 and opened[0].startswith("Happiness"), str(opened))
        await pg.click("#exp-sub button[data-sub=rounds]"); await pg.wait_for_timeout(200)
        await pg.click("#exp-rounds .lanecard.ours .plink >> nth=0"); await pg.wait_for_timeout(300)
        t = await pg.inner_text("#exp-players")
        check("player link opens their history, with a way back to Rounds", "Back to Rounds" in await pg.inner_text("#player-back"))
        await pg.click("#player-back"); await pg.wait_for_timeout(300)
        st = await pg.evaluate("[document.querySelector('#exp-sub button[aria-pressed=true], #exp-sub button.on')?.dataset.sub, document.getElementById('exp-rounds').hidden, document.getElementById('exp-rounds').offsetHeight, !!document.getElementById('player-back')]")
        check("back from a player returns to Rounds", not await pg.is_hidden("#exp-rounds") and await pg.is_hidden("#player-back"), str(st))
        await pg.click("#exp-sub button[data-sub=rounds]"); await pg.wait_for_timeout(200)
        await pg.click("#exp-week-head .linkbtn >> text=ArchAcademy"); await pg.wait_for_timeout(300)
        check("ArchAcademy link opens roster", not await pg.is_hidden("#view-roster"))
        await pg.click("#tab-expedition"); await pg.wait_for_timeout(200)
        # opponents
        await pg.click("#exp-sub button[data-sub=opponents]"); await pg.wait_for_timeout(200)
        t = await pg.inner_text("#exp-opponents")
        check("opponents default to the selected week", "Holymoly" in t and "UkraineArchers" in t and "Whispers" not in t and "PWNZ" not in t, t[:300])
        await pg.click("#opp-all"); await pg.wait_for_timeout(200)
        t = await pg.inner_text("#exp-opponents")
        check("opponents listed", all(k in t for k in ["Holymoly", "Happiness", "Whispers", "PWNZ", "BlockMagic"]))
        await pg.evaluate("[...document.querySelectorAll('#exp-opponents details.inv')].find(d=>d.querySelector('summary').innerText.startsWith('Happiness')).open=true"); await pg.wait_for_timeout(200)
        await pg.screenshot(path="/tmp/shots/exp-opp.png", full_page=False)
        t = await pg.inner_text("#exp-opponents")
        check("opponent lane history + scan", "lane history" in t.lower() and "KiLess" in t and "roster scan" in t.lower())
        # players
        await pg.click("#exp-sub button[data-sub=players]"); await pg.wait_for_timeout(200)
        first = await pg.inner_text("#exp-players tbody tr:first-child td:first-child")
        check("players sorted by DPS avg", first.strip() == "Hago26", first)
        so = await pg.locator("#exp-players .so").count()
        check("standouts shown", 1 <= so <= 12, str(so))
        await pg.screenshot(path="/tmp/shots/exp-players.png", full_page=False)
        await pg.click("#players-table thead th:last-child .sortbtn"); await pg.wait_for_timeout(100)
        top = await pg.inner_text("#exp-players tbody tr:first-child")
        print("   top change row:", top.replace("\n", " ")[:160])
        await pg.screenshot(path="/tmp/shots/exp-players.png", full_page=False)
        await pg.click("#exp-players tbody tr:first-child"); await pg.wait_for_timeout(200)
        t = await pg.inner_text("#exp-players")
        check("player detail rounds", "vs lane" in t and "Week of Nov" in t)
        await pg.screenshot(path="/tmp/shots/exp-player-detail.png", full_page=False)
        # findings
        await pg.click("#exp-sub button[data-sub=findings]"); await pg.wait_for_timeout(200)
        t = await pg.inner_text("#exp-findings")
        check("findings + estimate check", "Gear set" in t and "Strength estimate check" in t, t[t.find("Strength"):t.find("Strength")+200])
        # roster DPS from expedition
        await pg.click("#tab-roster"); await pg.wait_for_timeout(300)
        await pg.fill("#roster-search", "michelo"); await pg.wait_for_timeout(100)
        rt = await pg.inner_text("#roster-body")
        check("roster Avg DPS from expedition data, with units", "165 K/s" in rt, rt[-60:])
        # new week
        await pg.click("#tab-expedition"); await pg.click("#exp-new-week"); await pg.wait_for_timeout(100)
        dv = await pg.eval_on_selector("#exp-new-week-box input[aria-label='Week starting']", "i=>i.value")
        check("new week defaults to the Tuesday after the latest week", dv == "2026-11-24", dv)
        await pg.click("#exp-new-week-box >> text=Cancel"); await pg.wait_for_timeout(100)
        check("Cancel closes the panel", await pg.is_hidden("#exp-new-week-box"))
        await pg.click("#exp-new-week"); await pg.wait_for_timeout(100)
        await pg.click("text=Create week"); await pg.wait_for_timeout(400)
        weeks = await pg.eval_on_selector("#exp-week", "s=>[...s.options].map(o=>o.text)")
        check("new week created", len(weeks) == 4, str(weeks))
        await pg.click("#exp-sub button[data-sub=opponents]"); await pg.wait_for_timeout(200)
        t = await pg.inner_text("#exp-opponents")
        ph = await pg.get_attribute("#opp-new-name", "placeholder")
        check("new week: add form with 0 of 3", "0 of 3 added" in t and ph == "New opponent guild name", t[:200])
        for g in ["Happiness", "NewGuildA", "NewGuildB"]:
            await pg.fill("#opp-new-name", g); await pg.click("#opp-add"); await pg.wait_for_timeout(300)
        t = await pg.inner_text("#exp-opponents")
        check("form closes at 3 opponents", await pg.locator("#opp-new-name").count() == 0 and "All 3 opponents for this week are set" in t, t[:200])
        hw = await pg.evaluate("Object.values(Object.fromEntries(window.__store)).filter(v=>v&&v.name==='Happiness').map(v=>v.weeks)")
        nw = hw[0][-1] if hw and hw[0] else ""   # the new week's id depends on today's date
        hc = await pg.locator(f"#opp-list > details[data-guild='Happiness'][data-week='{nw}']").count(); hs = await pg.eval_on_selector_all("#opp-list > details > summary", "s=>s.map(x=>x.innerText)")
        check("existing guild attached, not duplicated", len(hw) == 1 and hw[0][:2] == ["2026-11-02", "2026-11-16"] and len(hw[0]) == 3 and nw == "2026-11-24" and hc == 1, f"{hw} {hc} {hs}")
        check("no JS errors", not errs, str(errs))
        await b.close()
    print(sum(res), "/", len(res))
asyncio.run(main())
